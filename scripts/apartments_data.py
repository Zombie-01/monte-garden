apts = []
for pid, (rooms, variant, total, legend) in PLANS.items():
    mk = M[pid]['markers']
    n = len(legend)
    # resolve misreads: duplicates / out-of-range numbers go to the missing numbers, lowest confidence first
    by_num = {}
    for m in sorted(mk, key=lambda m: -m['conf']):
        if 1 <= m['n'] <= n and m['n'] not in by_num:
            by_num[m['n']] = m
    missing = [k for k in range(1, n + 1) if k not in by_num]
    spare = [m for m in mk if all(m is not v for v in by_num.values())]
    for m in spare:
        if not missing:
            break
        k = m['alt'] if m['alt'] in missing else missing[0]
        missing.remove(k)
        by_num[k] = m
    W_, H_ = M[pid]['size']
    rooms_out = []
    for i, (name, area) in enumerate(legend, 1):
        m = by_num.get(i)
        rooms_out.append({'n': i, 'name': name, 'area': area, 'x': round(m['x'] / W_, 4) if m else None, 'y': round(m['y'] / H_, 4) if m else None})
    apts.append({'id': pid, 'rooms': rooms, 'variant': variant, 'total': total, 'list': rooms_out})
    if missing:
        print(pid, 'no marker for', missing)

apts.sort(key=lambda a: (a['rooms'], a['total']))
open(out, 'w').write('// Generated by scripts/apartments_data.py from the developer floor-plan posters (research/rooms).\nexport const APARTMENTS = ' + json.dumps(apts, ensure_ascii=False, indent=1) + ';\n')
